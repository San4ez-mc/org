/**
 * Шаблони документів, які асистент робить для клієнта.
 *
 * Тут лежать ЗАГОТОВКИ, а не остаточні тексти. Сенс такий: у кожного клієнта є
 * свій усталений вигляд лонгліста чи комерційної — і він майже завжди кращий за
 * вигаданий нами, бо перевірений його ринком. Тому платформа кладе заготовку в
 * теку клієнта звичайним Google-документом, клієнт правит її під себе руками,
 * а асистент далі бере ЙОГО версію.
 *
 * Через це шаблон — дані, а не текст у промпті: промпт правити може тільки
 * розробник, документ на Диску — сама власниця, будь-якого вечора.
 */

export interface DocumentTemplate {
  /** Ключ, яким асистент просить шаблон. */
  kind: string;
  /** Назва документа-заготовки на Диску. */
  title: string;
  /** Коли цей документ доречний — щоб асистент не плутав лонглист із довідкою. */
  when: string;
  /** Куди класти готовий документ (тека з областей запису). */
  folder: string;
  /** Сама заготовка. Маркдаун: при записі перетворюється на стилі Google Docs. */
  skeleton: string;
}

