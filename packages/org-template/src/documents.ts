/** Тека з шаблонами всередині спільних документів компанії. */
export const TEMPLATES_FOLDER = 'Шаблони документів';

export function findTemplate(kind: string): DocumentTemplate | undefined {
  const k = String(kind || '').trim().toLowerCase();
  return DOCUMENT_TEMPLATES.find((t) => t.kind === k);
}

/** Перелік для промпту: що взагалі можна зробити і коли. */
export function templatesForPrompt(): string {
  return DOCUMENT_TEMPLATES.map((t) => `${t.kind} — ${t.title}. Коли: ${t.when}. Тека: ${t.folder}.`).join('\n');
}
