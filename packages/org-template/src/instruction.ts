/** Порожній каркас: створюється одразу, наповнюється потім. */
export function instructionSkeleton(postName: string, ckp?: string): string {
  const head = `Посадова інструкція — ${postName}\n`;
  const body = INSTRUCTION_SECTIONS.map((s) => {
    if (s.key === 'ckp' && ckp) return `## ${s.title}\n${ckp}\n`;
    return `## ${s.title}\n_(заповнюється)_\n`;
  }).join('\n');
  return `${head}\n${body}`;
}

/** Опис структури для промпту генератора — щоб не дублювати його в кожній воронці. */
export function instructionSpecForPrompt(): string {
  return INSTRUCTION_SECTIONS
    .map((s, i) => `${i + 1}. ${s.title}${s.optional ? ' (за наявності даних)' : ''}\n   ${s.purpose}`)
    .join('\n');
}
