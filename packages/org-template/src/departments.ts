/** Звідки взявся відділ — щоб було видно, що з цього придумав бот. */
export type DepartmentOrigin = 'CANONICAL' | 'TYPICAL' | 'CUSTOM';

export interface KnownDepartment {
  name: string;
  ckp: string;
  origin: 'CANONICAL' | 'TYPICAL';
  when?: string;
}

/** Усе, що система знає про відділи цього відділення: базові плюс типові. */
export function knownDepartments(divisionBoardNo: number): KnownDepartment[] {
  const canon = CANONICAL_DIVISIONS.find((d) => d.boardNo === divisionBoardNo);
  return [
    ...(canon?.departments ?? []).map((d) => ({ name: d.name, ckp: d.ckp, origin: 'CANONICAL' as const })),
    ...TYPICAL_DEPARTMENTS.filter((d) => d.divisionBoardNo === divisionBoardNo).map((d) => ({
      name: d.name, ckp: d.ckp, origin: 'TYPICAL' as const, when: d.when,
    })),
  ];
}

/** Каталог відділень з відділами для промпту класифікатора. */
export function boardForPrompt(): string {
  return [...CANONICAL_DIVISIONS]
    .sort((a, b) => a.boardNo - b.boardNo)
    .map((d) => {
      const lines = knownDepartments(d.boardNo).map(
        (x) => `      · ${x.name} — ${x.ckp}` + (x.when ? ` [доречний, якщо ${x.when}]` : ''),
      );
      return `${d.boardNo}. ${d.name}\n   ЦКП відділення: ${d.ckp}\n   Відділи:\n${lines.join('\n')}`;
    })
    .join('\n\n');
}
